from langchain_google_genai import ChatGoogleGenerativeAI


LLM_MODEL = "gemini-2.5-flash"


def orchestrate_analysis(
    financial_analysis: str,
    business_analysis: str
    ) -> str:

    llm = ChatGoogleGenerativeAI(
        model=LLM_MODEL, temperature=0
    )

    prompt = f"""
あなたは金融機関の融資審査担当者です。
財務分析と事業・業界分析を統合し、融資審査のための内部分析を行ってください。

以下の「財務分析」と「事業・業界分析」の2つの分析結果をもとに、
当該企業について総合的な企業分析を行い、融資判断をしてください。

分析結果は企業への説明ではなく、
金融機関内部の融資審査における分析・判断として記載してください。

【財務分析】
{financial_analysis}

【事業・業界分析】
{business_analysis} 

以下の観点から総合的に評価してください。
各項目は2～3点程度の箇条書きで簡潔にまとめてください。
単に2つの分析結果を再掲・要約するのではなく、
財務面と事業面を関連付け、融資審査上どのように評価すべきかを示してください。

1. 事業の安定性
2. 事業の成長性
3. 収益力
4. 財務健全性
5. 主要なリスク
6. 返済能力
7. 総合的な信用力

特に「返済能力」については、財務分析を中心に評価してください。

そのうえで、金融機関としての融資判断を以下のいずれかから示してください。

・融資に前向き
・条件付きで融資に前向き
・慎重に判断
・融資には否定的

融資判断では、財務面と事業面の双方を考慮し、
それぞれの強みとリスクが融資判断にどのように影響するかを具体的に説明してください。

また、融資を行う場合には、
金融機関として今後モニタリングすべき事項を示してください。
強みだけでなく、融資判断上の懸念事項も必ず明示してください。
融資判断と、その判断を覆す可能性があるリスクは区別してください。
追加で確認すべき事項がある場合は明示してください。
分析結果に記載されていない事実を推測して補完しないでください。
「極めて」「非常に」「圧倒的」など、根拠以上に強い表現は避けてください。
元の分析結果に記載された情報を根拠として、
金融機関としての融資判断に必要な範囲で評価してください。
"""
    
    response = llm.invoke(prompt)

    return response.content