from langchain_google_genai import ChatGoogleGenerativeAI


LLM_MODEL = "gemini-2.5-flash"


def analyze_business(business_text: str) -> str:

    llm = ChatGoogleGenerativeAI(
        model=LLM_MODEL,
        temperature=0
    )


    prompt = f"""
あなたは企業の事業分析・業界分析の専門家です。 

以下は、企業の有価証券報告書における「事業の状況」の記載内容です。

この情報をもとに、当該企業が属する業界および事業環境について分析してください。
各項目3〜5点程度に簡潔にまとめること。

【分析項目】
1. 企業が属する業界・事業領域
2. 主な事業内容
3. 市場・需要の動向
4. 競争環境
5. 業界・事業特有のリスク
6. 当該企業が直面している経営課題
7. 今後の業界・事業環境の見通し

特に以下の点を意識してください。
・企業自身が認識している事業環境や経営課題を整理する
・企業固有の問題と、業界全体に共通する問題を可能な限り区別する
・単なる事業内容の要約ではなく、業界環境が当該企業の事業や業績にどのような影響を与える可能性があるかを考察する
・当該企業の競争優位性や成長可能性について、事業面から分析する
・当該企業が抱える事業上のリスクについて整理する
・記載されていない情報については推測で補完せず、与えられた情報から合理的に判断できる範囲で分析する
・財務数値に基づく評価や融資判断は行わず、事業・業界の観点から分析する

【事業の状況】
{business_text} 

上記を踏まえて、金融機関が後続の融資審査に利用できるよう、
事業・業界の観点から具体的かつ簡潔に分析してください。
"""
    
    response = llm.invoke(prompt)

    return response.content