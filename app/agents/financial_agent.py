from langchain_google_genai import ChatGoogleGenerativeAI


LLM_MODEL = "gemini-2.5-flash"


def analyze_financial_statement(financial_text: str) -> str:

    llm = ChatGoogleGenerativeAI(
        model=LLM_MODEL,
        temperature=0
    )


    prompt = f"""
あなたは企業財務分析の専門家です。

以下は、有価証券報告書から抽出した「経理の状況」から
「提出会社の株式事務の概要」までの情報です。

この情報をもとに、企業の財務状況を分析してください。
ただし、数値そのものではなく、財務分析上重要な変化・原因・意味を優先し、
各項目3〜5点程度に簡潔にまとめること。

【分析項目】
1. 売上高・営業利益・経常利益・当期純利益の推移
- 各利益の推移から、業績の特徴や重要な変化を分析する
- 単純な前年比や数値の列挙は避ける
- 売上と各利益の伸び率の違いなど、経営上意味のある点を説明する

2. 収益性
- 売上総利益率、営業利益率、経常利益率などの変化を分析する
- 利益率の変化から、収益構造やコスト面の特徴を説明する
- 単純な利益率の提示にとどめず、その背景や経営上の意味を説明する

3. 財務安全性
- 自己資本比率、流動比率、負債の状況、現金及び預金などから財務基盤を分析する
- 財務指標を単純に列挙せず、企業の支払能力や財務上の安定性を評価する
- 特に重要な変化がある場合は、その要因や意味を説明する

4. キャッシュフロー
- 営業CF・投資CF・財務CFの構成から、資金創出力や資金の使途を分析する
- 単純な数値の列挙は避け、キャッシュフローの変化が示す企業の特徴を説明する
- 営業CFの変化については、利益だけでなく運転資本などの要因も考慮する

5. 特に注目すべき財務上の変化
- 上記の分析を踏まえ、特に重要または特徴的な財務上の変化を抽出する
- 業績、収益性、財務安全性、キャッシュフローの中から、経営上重要な事項を優先する
- 一時的な要因や将来への影響が考えられる事項についても、根拠に基づいて説明する

6. 総合評価
- 業績、収益性、財務安全性、キャッシュフローを踏まえて総合的に評価する
- 強みと注意すべき点をそれぞれ示す
- 単なる分析結果の繰り返しではなく、企業の財務状況を総合的に評価する

--- 有価証券報告書 ---
{financial_text}
"""
    
    response = llm.invoke(prompt)

    return response.content